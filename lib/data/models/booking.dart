/// Values of the `public.booking_status` enum. There is no "pending",
/// "paid" or "completed" status in the database, so none is modelled.
enum BookingStatus { confirmed, cancelled }

/// Destination fields embedded in a booking row (via `destination_id`).
class BookingDestination extends Equatable {
  const BookingDestination({
    required this.id,
    required this.nameEn,
    required this.nameAr,
    required this.countryEn,
    required this.countryAr,
    required this.coverImage,
  });

  factory BookingDestination.fromJson(Map<String, dynamic> json) => BookingDestination(
        id: json.str('id'),
        nameEn: json.str('name_en'),
        nameAr: json.str('name_ar'),
        countryEn: json.str('country_en'),
        countryAr: json.str('country_ar'),
        coverImage: json.str('cover_image'),
      );

  final String id;
  final String nameEn;
  final String nameAr;
  final String countryEn;
  final String countryAr;
  final String coverImage;

  String name(String languageCode) => pickLocalized(languageCode, en: nameEn, ar: nameAr);
  String country(String languageCode) => pickLocalized(languageCode, en: countryEn, ar: countryAr);

  @override
  List<Object?> get props => [id, nameEn, nameAr, coverImage];
}

/// Package fields embedded in a booking row (via `package_id`).
class BookingPackage extends Equatable {
  const BookingPackage({required this.id, required this.nameEn, required this.nameAr, required this.durationDays});

  factory BookingPackage.fromJson(Map<String, dynamic> json) => BookingPackage(
        id: json.str('id'),
        nameEn: json.str('name_en'),
        nameAr: json.str('name_ar'),
        durationDays: json.intOrNull('duration_days') ?? (throw const FormatException('Missing duration_days')),
      );

  final String id;
  final String nameEn;
  final String nameAr;
  final int durationDays;

  String name(String languageCode) => pickLocalized(languageCode, en: nameEn, ar: nameAr);

  @override
  List<Object?> get props => [id, nameEn, nameAr, durationDays];
}

/// A row of `public.bookings`. Prices, currency, reference and status are
/// always the values the database computed — never client-side guesses.
class Booking extends Equatable {
  const Booking({
    required this.id,
    required this.reference,
    required this.destinationId,
    required this.packageId,
    required this.travelDate,
    required this.travelers,
    required this.unitPrice,
    required this.totalPrice,
    required this.currency,
    required this.status,
    required this.contactName,
    required this.contactPhone,
    required this.createdAt,
    this.specialRequests,
    this.cancelledAt,
    this.destination,
    this.package,
  });

  factory Booking.fromJson(Map<String, dynamic> json) {
    final statusName = json.str('status');
    final status = BookingStatus.values.where((s) => s.name == statusName).firstOrNull ??
        (throw FormatException('Unknown booking status', statusName));
    final travelers = json.intOrNull('travelers');
    if (travelers == null || travelers < 1) throw FormatException('Invalid travelers', json['travelers']);

    Map<String, dynamic>? embedded(String key) {
      final value = json[key];
      if (value == null) return null;
      if (value is Map<String, dynamic>) return value;
      throw FormatException('Expected object for "$key"', value);
    }

    final destinationJson = embedded('destination');
    final packageJson = embedded('package');
    return Booking(
      id: json.str('id'),
      reference: json.str('reference'),
      destinationId: json.str('destination_id'),
      packageId: json.str('package_id'),
      travelDate: parseDateOnly(json.str('travel_date')),
      travelers: travelers,
      unitPrice: json.number('unit_price'),
      totalPrice: json.number('total_price'),
      // char(3) may come back padded.
      currency: json.str('currency').trim(),
      status: status,
      contactName: json.str('contact_name'),
      contactPhone: json.str('contact_phone'),
      specialRequests: json.strOrNull('special_requests'),
      createdAt: json.dateOrNull('created_at') ?? (throw const FormatException('Missing created_at')),
      cancelledAt: json.dateOrNull('cancelled_at'),
      destination: destinationJson == null ? null : BookingDestination.fromJson(destinationJson),
      package: packageJson == null ? null : BookingPackage.fromJson(packageJson),
    );
  }

  final String id;

  /// Human-readable reference generated by the database (e.g. `RH-3F9A1C2B`).
  final String reference;
  final String destinationId;
  final String packageId;

  /// Calendar date (no time zone), as stored in the `date` column.
  final DateTime travelDate;
  final int travelers;
  final double unitPrice;
  final double totalPrice;
  final String currency;
  final BookingStatus status;
  final String contactName;
  final String contactPhone;
  final String? specialRequests;
  final DateTime createdAt;
  final DateTime? cancelledAt;

  /// `null` if the destination/package is no longer visible in the catalog.
  final BookingDestination? destination;
  final BookingPackage? package;

  bool get isCancelled => status == BookingStatus.cancelled;

  /// Confirmed and the travel date hasn't passed ([today] is a date).
  bool isUpcoming(DateTime today) => !isCancelled && !travelDate.isBefore(today);

  /// Confirmed and the travel date has passed. Labelled "Past" in the UI —
  /// the database has no "completed" status.
  bool isPast(DateTime today) => !isCancelled && travelDate.isBefore(today);

  /// Mirrors `cancel_booking`: confirmed and travelling after [today]. The
  /// server re-checks and is the authority.
  bool canCancel(DateTime today) => !isCancelled && travelDate.isAfter(today);

  /// The same booking with the server's cancellation result, keeping the
  /// embedded catalog data the RPC response doesn't include.
  Booking withStatusFrom(Booking server) => Booking(
        id: id,
        reference: reference,
        destinationId: destinationId,
        packageId: packageId,
        travelDate: server.travelDate,
        travelers: server.travelers,
        unitPrice: server.unitPrice,
        totalPrice: server.totalPrice,
        currency: server.currency,
        status: server.status,
        contactName: server.contactName,
        contactPhone: server.contactPhone,
        specialRequests: server.specialRequests,
        createdAt: server.createdAt,
        cancelledAt: server.cancelledAt,
        destination: server.destination ?? destination,
        package: server.package ?? package,
      );

  @override
  List<Object?> get props =>
      [id, reference, status, travelDate, travelers, totalPrice, cancelledAt, destination, package];
}

/// What the traveller chose. Only these fields are sent — they're exactly the
/// columns the `authenticated` role may insert. Owner, prices, currency,
/// reference and status are set by the database.
class BookingRequest extends Equatable {
  const BookingRequest({
    required this.destinationId,
    required this.packageId,
    required this.travelDate,
    required this.travelers,
    required this.contactName,
    required this.contactPhone,
    this.specialRequests,
    this.clientRequestId,
  });

  final String destinationId;
  final String packageId;
  final DateTime travelDate;
  final int travelers;
  final String contactName;
  final String contactPhone;
  final String? specialRequests;

  /// Idempotency key: one per booking attempt, reused for every retry of it.
  /// The database rejects a second row with the same (owner, key).
  final String? clientRequestId;

  String? get _notes {
    final notes = specialRequests?.trim();
    return (notes == null || notes.isEmpty) ? null : notes;
  }

  /// Identifies "the same booking attempt" independently of the request id,
  /// so a retry — even after an app restart — maps to the same id. Hashed so
  /// contact details aren't stored in plain text on the device.
  String get fingerprint => stableDigest([
        destinationId,
        packageId,
        formatDateOnly(travelDate),
        '$travelers',
        contactName.trim(),
        contactPhone.trim(),
        _notes ?? '',
      ].join('\u0001'));

  BookingRequest withClientRequestId(String id) => BookingRequest(
        destinationId: destinationId,
        packageId: packageId,
        travelDate: travelDate,
        travelers: travelers,
        contactName: contactName,
        contactPhone: contactPhone,
        specialRequests: specialRequests,
        clientRequestId: id,
      );

  /// True when [booking] is the stored result of this same request.
  bool matches(Booking booking) =>
      booking.destinationId == destinationId &&
      booking.packageId == packageId &&
      booking.travelDate == DateTime(travelDate.year, travelDate.month, travelDate.day) &&
      booking.travelers == travelers;

  Map<String, dynamic> toInsertJson() => {
        'destination_id': destinationId,
        'package_id': packageId,
        'travel_date': formatDateOnly(travelDate),
        'travelers': travelers,
        'contact_name': contactName.trim(),
        'contact_phone': contactPhone.trim(),
        'special_requests': _notes,
        if (clientRequestId != null) 'client_request_id': clientRequestId,
      };

  @override
  List<Object?> get props =>
      [destinationId, packageId, travelDate, travelers, contactName, contactPhone, specialRequests, clientRequestId];
}

/// `YYYY-MM-DD` → a date-only [DateTime] (local midnight, no time zone shift).
DateTime parseDateOnly(String value) {
  final match = RegExp(r'^(\d{4})-(\d{2})-(\d{2})$').firstMatch(value);
  if (match == null) throw FormatException('Expected YYYY-MM-DD', value);
  return DateTime(int.parse(match[1]!), int.parse(match[2]!), int.parse(match[3]!));
}

String formatDateOnly(DateTime date) =>
    '${date.year.toString().padLeft(4, '0')}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')}';

/// "Today" as the database sees it: Postgres `current_date` runs in UTC on
/// Supabase. Booking-date limits and cancellation use this, not the device's
/// local date, so the app and the server agree.
DateTime serverToday([DateTime? now]) {
  final utc = (now ?? DateTime.now()).toUtc();
  return DateTime(utc.year, utc.month, utc.day);
}
